using Microsoft.AspNetCore.Identity;

namespace CivicEyeGD.Data;

// Начинът, по който собственикът на профил доказва самоличността си,
// когато паролата е загубена. Пощенски сървър в проекта няма, затова
// възстановяването не може да тръгне по имейл; остава нещо, което
// человекът знае и може да въведе сам.
//
// Един ред на профил, а не списък с няколко въпроса: при един въпрос
// правилото за проверка е ясно (избраният трябва да съвпада), а
// повърхността за отгатване не се умножава.
//
// Отговорът не се пази като текст, а като хеш със случайна сол. Тази
// таблица живее в същия SQLite файл като сигналите; ако файлът изтече,
// от него не трябва да може да се влезе в нито един профил.
public class RecoveryQuestion
{
    // Първичният ключ е едновременно и собственикът: един профил има
    // един въпрос, а изтриването на профила води редовете му със себе си.
    public string UserId { get; set; } = string.Empty;
    public IdentityUser User { get; set; } = null!;

    // Стабилният идентификатор на въпроса („first-pet“), не изписаният
    // текст. Така формулировките могат да се препишат без миграция и
    // без чужди текстове да се озовават в базата.
    public string QuestionKey { get; set; } = string.Empty;

    // Случайните байтове, с които отговорът се разбърква преди
    // хеширането. Те са обществени (един и същ отговор при различна
    // сол дава различен ред) и са нужни, за да не може двама потребители
    // с еднакъв отговор да се разпознаят един по друг.
    public string AnswerSalt { get; set; } = string.Empty;

    // Самото доказателство: бавен хеш на нормализирания отговор.
    public string AnswerHash { get; set; } = string.Empty;

    // UTC, както навсякъде в базата: при смяна на часовата зона редът
    // трябва да остава на своето място в хронологията.
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
}
