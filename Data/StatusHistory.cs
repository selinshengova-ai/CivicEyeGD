using Microsoft.AspNetCore.Identity;

namespace CivicEyeGD.Data;

// Дневникът на сигнала. Един ред тук е една видима намеса на общината,
// затова страницата на сигнала показва не само кога сигналът е прехвърлен
// от статус в статус, но и кога е променяно числото на приоритета и каква
// бележка е оставена. Редовете не се изтриват и не се поправят:
// историята е доказателство, а не текущо състояние.
public class StatusHistory
{
    public int Id { get; set; }

    public int ReportId { get; set; }
    public Report Report { get; set; } = null!;

    // Двата статуса са равни, когато служителят е оставил само бележка или
    // е коригирал приоритета. От това страницата на сигнала разбира, че
    // записът не е преход между статуси. Старият статус е с разрешена
    // липса, защото редът може да не описва смяна на статус изобщо.
    public string? OldStatus { get; set; }
    public string NewStatus { get; set; } = string.Empty;

    // Кой е натиснал бутона. Идентификаторът е с разрешена липса, защото
    // потребител може да бъде изтрит, а историята на сигнала не трябва да
    // изчезва заедно с акаунта на автора си.
    public string? ChangedByUserId { get; set; }
    public IdentityUser? ChangedByUser { get; set; }

    // Времето се пази в UTC: на екрана се превръща в местното, а запис с
    // местно време би объркал реда на събитията при смяна на часовата зона.
    public DateTime ChangedAt { get; set; } = DateTime.UtcNow;

    // Бележката е публична: гражданът я чете в историята на сигнала,
    // затова ReportOfficeService я съкращава до общата граница.
    public string? Comment { get; set; }

    // Двойката за корекцията на приоритета. Полетата се попълват само при
    // реална промяна, за да не се чете „7 → 7“ там, където нищо не е
    // местено. Без тях намесата в числото 0-100 би останала невидима.
    public int? OldPriorityAdjustment { get; set; }
    public int? NewPriorityAdjustment { get; set; }
}
