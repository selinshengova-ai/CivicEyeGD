using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Identity;

namespace CivicEyeGD.Data;

// Една оценка на един гражданин за един сигнал: колко сериозен му
// се вижда проблемът. Ред за всеки глас, не сборна стойност — така
// средното се пресмята живо и може да се отстрани гласът на подателя
// (вж. Report.IndependentRatings); запазено средно би остаряло при
// всяка нова оценка и би крило кой точно го е променил.
public class SeverityRating
{
    public int Id { get; set; }

    // Сигналът, който се оценява; двойката (ReportId, UserId) е
    // уникална в DbContext-а, затова един човек не може да тегли
    // везните с няколко профила-оценки върху един и същи сигнал.
    public int ReportId { get; set; }
    public Report Report { get; set; } = null!;

    // Кой е дал оценката. Без този идентификатор не може да се разбере
    // дали гласът е на подателя и да се отстрани от средното.
    public string UserId { get; set; } = string.Empty;
    public IdentityUser User { get; set; } = null!;

    // Скала 1..5 с цели числа: гражданинът избира бързо и без десетични
    // спорове, а формулата за приоритет умножава S по 20 точно за този
    // диапазон — максимумът 5 дава 100 точки от 140 възможни.
    // Средно независимите оценки 4.0 и нагоре правят сигнала „спешен“
    // на картата, затова 5 е реална стойност, а не хипербола.
    [Range(1, 5)]
    public int Rating { get; set; }

    // UTC, защото местният час скача при смяна на лятното часово време
    // и реда на оценките в историята би се наредил наопаки.
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
}