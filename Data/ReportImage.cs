
namespace CivicEyeGD.Data;

// Една снимка, прикачена към сигнал (Report).
// Самият файл се пази на диска ИЗВЪН wwwroot, а тук пазим само
// служебното име и метаданните. Реалният път до файла никога
// не се показва на потребителя.
public class ReportImage
{
    public int Id { get; set; }

    // Сигналът, към който принадлежи снимката.
    public int ReportId { get; set; }

    public Report Report { get; set; } = null!;

    // Служебно (генерирано) име на файла на диска: GUID + разширение.
    // Оригиналното име от потребителя НЕ се използва като име за съхранение.
    public string StoredFileName { get; set; } = string.Empty;

    // MIME типът, определен и потвърден на сървъра.
    // Типът идва от байтовите сигнатури на файла (ReportImageStorage),
    // а не от това, което браузърът е обявил — иначе преименуван
    // изпълним файл би минал като „изображение“.
    public string ContentType { get; set; } = string.Empty;

    // Размер на файла в байтове.
    // Записва се размерът СЛЕД прочистването на метаданните (EXIF с
    // GPS координати), затова може да е различен от качения от
    // потребителя файл — това е честният отговор на въпроса „колко“.
    public long SizeBytes { get; set; }

    // UTC както навсякъде в базата: местно време би объркало реда на
    // снимките при смяна на лятното часово време или при сървър в
    // друга часова зона.
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
}
