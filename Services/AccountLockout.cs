namespace CivicEyeGD.Services;

// Правилото за временно заключване на акаунт живее тук, а не в двете
// страници, които го съобщават: то казва колко опита се позволяват и
// колко трае изчакването, и същото число стои в настройката на Identity.
// Ако числата се препишат на трите места, рано или късно ще са различни,
// а човекът ще чака по-малко или повече от казаното.
public static class AccountLockout
{
    public const int FailedAttempts = 5;
    public const int WaitMinutes = 10;

    // Текстът, който влиза в ModelState при вход и при възстановяване на
    // паролата: и двете страници заключват по едно и също правило, затова
    // и обяснението е едно и също.
    public static string Message =>
        $"Акаунтът е временно заключен след {FailedAttempts} неуспешни опита. "
        + $"Опитай отново след {WaitMinutes} минути.";
}
