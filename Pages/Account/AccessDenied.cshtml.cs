using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;

namespace CivicEyeGD.Pages.Account;

// Identity насам препраща влезъл потребител, който поиска страница
// само за администратор. Без тази страница пренасочването се превръща
// в 404 и човек не разбира какво се е случило.
//
// Адресът не е записан изрично никъде в Program.cs: файлът е точно на
// това място и с това име, защото съвпада с подразбираната страница
// за отказан достъп, която бисквитата за вход ползва сама.
//
// Страницата, която съобщава за липса на права, не бива сама да ги
// изисква: иначе отказът се превръща в пренасочване към входа, а той
// — обратно към отказ и така нататък.
[AllowAnonymous]

// Не се кешира: запазено „нямаш достъп“ би се показвало и на колегата
// с права, или на същия човек след като е получил роля.
[ResponseCache(Duration = 0, Location = ResponseCacheLocation.None, NoStore = true)]

// Страницата само показва съобщение и няма форма, затова тук няма
// какво да пази предпазният токен; проверката е свалена, за да не
// излезе нова грешка отгоре на обяснението за правата.
[IgnoreAntiforgeryToken]
public class AccessDeniedModel : PageModel
{
    // Празен метод: текстът е неподвижен в изгледа, няма модел и няма
    // заявка към базата. Нищо лично не се издава — страницата казва
    // само че правата не стигат, а не кой точно ги има.
    public void OnGet()
    {
    }
}
