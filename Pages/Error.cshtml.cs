using System.Diagnostics;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;

namespace CivicEyeGD.Pages;

// Единна страница за всички грешки: насам водят и
// UseStatusCodePagesWithReExecute("/Error", "?code={0}"), и
// UseExceptionHandler("/Error"). Вместо празен екран или технически
// детали посетителят получава кратко обяснение на български.
//
// Позволена е без вход: ако тя самата паднеше под FallbackPolicy,
// всеки проблем се превръщаше в пренасочване към формата за вход.
[AllowAnonymous]

// Грешката не се кешира: запазена в браузъра или в междинен сървър,
// тя би се показвала и след като проблемът вече е отстранен.
[ResponseCache(Duration = 0, Location = ResponseCacheLocation.None, NoStore = true)]

// Изпълнява се отново в рамките на същата заявка, понякога след POST,
// чийто предпазен токен вече е използван. Втора проверка щеше да
// добави ново съобщение отгоре на истинската грешка.
[IgnoreAntiforgeryToken]
public class ErrorModel : PageModel
{
    // Номер на заявката: същият стои и в дневника на сървъра, затова
    // посетителят го цитира и служителят намира записа без други
    // въпроси. Самият номер не разкрива нито съдържанието на заявката,
    // нито нещо за вътрешността на приложението.
    public string? RequestId { get; set; }

    // Редът с номера се показва само когато наистина има номер.
    public bool ShowRequestId => !string.IsNullOrEmpty(RequestId);

    // Кодът се пази отделно, защото се използва и за заглавието, и за
    // етикета „CIVICEYE GD · ГРЕШКА <код>“ в изгледа.
    public int StatusCodeValue { get; private set; }

    // Заглавието и описанието имат стойност по подразбиране: ако кодът
    // е необичаен, страницата остава с общ текст, а не с празни полета.
    // Променят се само вътре в класа (private set) — изгледът чете, а
    // кое съобщение се показва се решава единствено тук.
    public string Title { get; private set; } = "Неочаквана грешка";

    public string Description { get; private set; } =
        "Заявката не можа да бъде обработена. Опитай отново след малко.";

    public void OnGet(int? code)
    {
        // Activity.Current?.Id е идентификаторът на проследяването,
        // с който се водат записите в дневника; TraceIdentifier е
        // резервен вариант, когато проследяването липсва.
        RequestId = Activity.Current?.Id ?? HttpContext.TraceIdentifier;

        // Параметър „code“ идва само от UseStatusCodePagesWithReExecute.
        // При неочаквано изключение пренасочването е към „/Error“ без
        // параметър, затова кодът се чете от вече зададения статус на
        // отговора. Един и същ метод обслужва и двата пътя.
        StatusCodeValue = code ?? HttpContext.Response.StatusCode;

        // Двойката се сменя наведнъж, за да не остане заглавие от един
        // код с описание от друг. Текстът е написан за гражданина:
        // какво се е случило и какво да направи, без имена на таблици,
        // класове или версии на .NET.
        (Title, Description) = StatusCodeValue switch
        {
            // 404 е най-честият случай: сгрешен адрес или препратка.
            404 => ("Страницата не е намерена",
                "Търсеният адрес не съществува в CivicEye GD."),
            403 => ("Нямаш достъп",
                "Тази част от системата е само за оторизирани потребители."),
            400 => ("Невалидна заявка",
                "Формата не е изпратена правилно. Опитай отново."),
            // При 500 и нагоре текстът не е само извинение:
            // ExceptionHandler записва изключението в дневника, преди
            // страницата изобщо да се изпълни, та обещанието е вярно.
            >= 500 => ("Грешка в сървъра",
                "Възникна проблем от наша страна. Той е записан в "
                + "дневника на сървъра, така че може да бъде проследен."),
            // Всички останали кодове остават с общия текст, за да няма
            // празна страница за рядък случай.
            _ => (Title, Description)
        };
    }
}
